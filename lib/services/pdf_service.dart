import 'dart:io';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:path_provider/path_provider.dart';
import '../models/wifi_network.dart';
import 'monetization_service.dart';

class PdfService {
  Future<File> generateReport(List<WiFiNetwork> networks, {String? testedSsid, Map<String, dynamic>? testResult}) async {
    final pdf = pw.Document();
    final now = DateTime.now();
    final isPro = MonetizationService().isPro;

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        header: (context) => pw.Container(
          padding: const pw.EdgeInsets.only(bottom: 8),
          decoration: const pw.BoxDecoration(border: pw.Border(bottom: pw.BorderSide(color: PdfColors.blueGrey100, width: 1))),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text('WanaLab WiFi Auditor', style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold, color: PdfColors.blue700)),
              pw.Text(isPro ? 'PRO Report - Licensed' : 'Free Version - WanaLab', style: pw.TextStyle(fontSize: 8, color: PdfColors.grey600)),
            ],
          ),
        ),
        footer: (context) => pw.Container(
          alignment: pw.Alignment.centerRight,
          margin: const pw.EdgeInsets.only(top: 10),
          child: pw.Text('Page ${context.pageNumber}/${context.pagesCount} | Generated by WanaLab - Wana, South Waziristan | wanadev.lab@gmail.com', style: const pw.TextStyle(fontSize: 7, color: PdfColors.grey)),
        ),
        build: (context) => [
          pw.Header(
            level: 0,
            child: pw.Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                pw.Text('WiFi Security Audit Report', style: pw.TextStyle(fontSize: 24, fontWeight: pw.FontWeight.bold, color: PdfColors.blue900)),
                pw.SizedBox(height: 4),
                pw.Text('Professional Technician Report - By WanaLab, Wana', style: pw.TextStyle(fontSize: 12, color: PdfColors.blueGrey700)),
              ],
            ),
          ),
          pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text('Date: ${now.toString().split('.')[0]}', style: const pw.TextStyle(fontSize: 11)),
                  pw.Text('Technician: Nasir Khan - WanaLab, Wana, S.Waziristan', style: const pw.TextStyle(fontSize: 11)),
                  pw.Text('Location: Wana, South Waziristan, KPK, Pakistan', style: const pw.TextStyle(fontSize: 9)),
                  pw.SizedBox(height: 2),
                  pw.Text('Generated 100% Offline - No Data Sent to Server', style: pw.TextStyle(fontSize: 9, color: PdfColors.green700, fontWeight: pw.FontWeight.bold)),
                ],
              ),
              pw.Container(
                padding: const pw.EdgeInsets.all(8),
                decoration: pw.BoxDecoration(color: isPro ? PdfColors.blue50 : PdfColors.grey100, borderRadius: pw.BorderRadius.circular(6)),
                child: pw.Text(isPro ? 'PRO VERSION\nWanaLab Licensed' : 'FREE VERSION\nUpgrade to remove watermark', textAlign: pw.TextAlign.center, style: pw.TextStyle(fontSize: 8, fontWeight: pw.FontWeight.bold, color: isPro ? PdfColors.blue800 : PdfColors.grey700)),
              ),
            ],
          ),
          pw.SizedBox(height: 20),

          pw.Container(
            padding: const pw.EdgeInsets.all(12),
            decoration: pw.BoxDecoration(color: PdfColors.blueGrey50, borderRadius: pw.BorderRadius.circular(8)),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text('Executive Summary:', style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 14)),
                pw.SizedBox(height: 6),
                pw.Text('Total Networks Scanned: ${networks.length}'),
                pw.Text('Critical Risk: ${networks.where((n) => n.riskLevel == RiskLevel.critical).length}', style: pw.TextStyle(color: PdfColors.red700, fontWeight: pw.FontWeight.bold)),
                pw.Text('High Risk: ${networks.where((n) => n.riskLevel == RiskLevel.high).length}', style: pw.TextStyle(color: PdfColors.orange700)),
                pw.Text('Medium: ${networks.where((n) => n.riskLevel == RiskLevel.medium).length}'),
                pw.Text('Secure: ${networks.where((n) => n.riskLevel == RiskLevel.secure).length}', style: pw.TextStyle(color: PdfColors.green700)),
              ],
            ),
          ),
          pw.SizedBox(height: 20),

          if (testedSsid != null && testResult != null) ...[
            pw.Container(
              padding: const pw.EdgeInsets.all(10),
              decoration: pw.BoxDecoration(border: pw.Border.all(color: testResult['isWeak'] == true ? PdfColors.red : PdfColors.green, width: 1.5), borderRadius: pw.BorderRadius.circular(6)),
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text('Authorized Own Network Password Test:', style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 12)),
                  pw.SizedBox(height: 4),
                  pw.Text('SSID: $testedSsid', style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
                  pw.Text('Score: ${testResult['score'] ?? testResult['strength']}/100 - ${testResult['level'] ?? ''}'),
                  pw.Text('Est. Crack Time: ${testResult['crackTime'] ?? 'N/A'}'),
                  pw.Text('Result: ${testResult['message']}', style: const pw.TextStyle(fontSize: 10)),
                  if (testResult['recommendations'] != null)
                    pw.Text('Fix: ${(testResult['recommendations'] as List).join(', ')}', style: const pw.TextStyle(fontSize: 9)),
                ],
              ),
            ),
            pw.SizedBox(height: 20),
          ],

          pw.Text('Detailed Findings (Sorted by Signal Strength):', style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 14)),
          pw.SizedBox(height: 10),

          ...networks.map((net) => pw.Container(
                margin: const pw.EdgeInsets.only(bottom: 10),
                padding: const pw.EdgeInsets.all(10),
                decoration: pw.BoxDecoration(
                  border: pw.Border.all(color: _getColorForRisk(net.riskLevel), width: 1),
                  borderRadius: pw.BorderRadius.circular(4),
                  color: _getBgForRisk(net.riskLevel),
                ),
                child: pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Row(
                      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                      children: [
                        pw.Text('SSID: ${net.ssid}', style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 12)),
                        pw.Container(
                          padding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 2),
                          decoration: pw.BoxDecoration(color: _getColorForRisk(net.riskLevel), borderRadius: pw.BorderRadius.circular(3)),
                          child: pw.Text(net.riskLabel.toUpperCase(), style: pw.TextStyle(color: PdfColors.white, fontSize: 8, fontWeight: pw.FontWeight.bold)),
                        ),
                      ],
                    ),
                    pw.SizedBox(height: 4),
                    pw.Text('BSSID: ${net.bssid} | Signal: ${net.signalStrength} dBm | Enc: ${net.encryptionType} | Band: ${net.band}', style: const pw.TextStyle(fontSize: 9)),
                    pw.SizedBox(height: 4),
                    pw.Text('Risks: ${net.risks.join(', ')}', style: const pw.TextStyle(fontSize: 10)),
                    pw.SizedBox(height: 2),
                    pw.Text('Recommendation: ${net.recommendation}', style: pw.TextStyle(fontSize: 9, fontStyle: pw.FontStyle.italic)),
                  ],
                ),
              )),
          pw.SizedBox(height: 20),
          if (!isPro)
            pw.Container(
              padding: const pw.EdgeInsets.all(8),
              color: PdfColors.yellow100,
              child: pw.Text('Free version watermark: Upgrade to WanaLab Pro (\$4.99) for client-ready reports without watermark + unlimited exports. From Wana, South Waziristan.', style: pw.TextStyle(fontSize: 9, color: PdfColors.orange900, fontWeight: pw.FontWeight.bold), textAlign: pw.TextAlign.center),
            ),
          pw.SizedBox(height: 10),
          pw.Divider(),
          pw.Text('Disclaimer: This report is for educational and authorized auditing only. Testing networks without owner permission is illegal under Pakistan PECA 2016 and international laws. Report generated offline - no data leaves device.', style: pw.TextStyle(fontSize: 7, color: PdfColors.grey600)),
          pw.SizedBox(height: 4),
          pw.Text('Independent project by Nasir Khan - WanaLab, Wana, South Waziristan, KPK, Pakistan. No data collected. Contact: wanadev.lab@gmail.com', style: pw.TextStyle(fontSize: 7, color: PdfColors.grey600)),
        ],
      ),
    );

    final dir = await getTemporaryDirectory();
    final file = File('${dir.path}/WanaLab_Audit_Wana_${now.millisecondsSinceEpoch}.pdf');
    await file.writeAsBytes(await pdf.save());
    return file;
  }

  PdfColor _getColorForRisk(RiskLevel level) {
    switch (level) {
      case RiskLevel.critical: return PdfColors.red700;
      case RiskLevel.high: return PdfColors.orange700;
      case RiskLevel.medium: return PdfColors.amber700;
      case RiskLevel.secure: return PdfColors.green700;
    }
  }

  PdfColor _getBgForRisk(RiskLevel level) {
    switch (level) {
      case RiskLevel.critical: return PdfColors.red50;
      case RiskLevel.high: return PdfColors.orange50;
      case RiskLevel.medium: return PdfColors.amber50;
      case RiskLevel.secure: return PdfColors.green50;
    }
  }
}
